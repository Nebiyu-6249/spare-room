"""Export Spare Room's own rules for the web playground: web/data/rules.json.

The playground on the site simulates the tool in the browser. So that the two
cannot drift apart, it does not carry its own copy of the rules: this script
dumps them from the Python source (locations, categories, severities, key-name
patterns, finding text, the fake laptop's targets) plus the trap fixtures in
traps/, file by file. It runs before every site build (web/package.json
"prebuild") and a test fails if the committed JSON is out of date.

Run from the repository root:  python packaging/export_rules.py [--check]
Nothing here reads a secret, touches the network or looks outside this repo.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from spareroom import TOOL_VERSION  # noqa: E402
from spareroom import locations as L  # noqa: E402
from spareroom.models import CATEGORIES, SEVERITIES  # noqa: E402
from spareroom.traps import DEMO_TARGETS, TRAPS  # noqa: E402

OUT = ROOT / "web" / "data" / "rules.json"
FAKE_HOME_USER = "testdev"  # demo_roots(): <fake laptop>/C/Users/testdev


def _trap_files(folder: str) -> list:
    base = ROOT / "traps" / folder
    files = []
    for p in sorted(base.rglob("*")):
        if p.is_file():
            rel = p.relative_to(base).as_posix()
            files.append({"path": rel, "text": p.read_text(encoding="utf-8").replace("\r\n", "\n")})
    # README first, the way the folder reads on GitHub.
    files.sort(key=lambda f: (f["path"] != "README.md", f["path"]))
    return files


def build() -> dict:
    return {
        "_note": "Generated by packaging/export_rules.py from spareroom/*.py and traps/. Do not edit by hand.",
        "tool_version": TOOL_VERSION,
        "categories": list(CATEGORIES),
        "severities": list(SEVERITIES),
        "specs": [
            {"id": s.id, "category": s.category, "check": s.check, "rel": list(s.rel) if s.rel else None,
             "kind": s.kind, "severity": s.severity, "reason": s.reason, "fix": s.fix, "source_ref": s.source_ref}
            for s in L.SPECS
        ],
        "npmrc_token_key_suffixes": list(L.NPMRC_TOKEN_KEY_SUFFIXES),
        "claude_files": [{"rel": list(rel), "kind": kind, "severity": sev} for rel, kind, sev in L.CLAUDE_FILES],
        "browsers": [{"name": name, "user_data": list(rel)} for name, rel in L.BROWSER_USER_DATA],
        "browser_profiles": list(L.BROWSER_PROFILES),
        "browser_local_state": dict(zip(("file", "kind", "severity", "reason"), L.BROWSER_LOCAL_STATE)),
        "browser_store_files": [dict(zip(("file", "kind", "severity", "reason"), f)) for f in L.BROWSER_STORE_FILES],
        "browser_fix": L.BROWSER_FIX,
        "browser_source_ref": L.SRC_T1555_003,
        "wallet_extensions": [{"id": k, "name": v} for k, v in L.WALLET_EXTENSIONS.items()],
        "wallet_ext": {"kind": L.WALLET_EXT_KIND, "severity": L.WALLET_EXT_SEVERITY, "reason": L.WALLET_EXT_REASON,
                       "fix": L.WALLET_EXT_FIX, "source_ref": L.SRC_UNIT42},
        "env": {"filenames": list(L.ENV_FILENAMES), "skip_dirs": sorted(L.ENV_SKIP_DIRS),
                "max_depth": L.ENV_MAX_DEPTH, "kind": L.ENV_KIND, "severity": L.ENV_SEVERITY,
                "reason": L.ENV_REASON, "fix": L.ENV_FIX, "source_ref": L.SRC_UNIT42},
        "fake_laptop": {"home_user": FAKE_HOME_USER,
                        "targets": [{"category": c, "rel": r} for c, r in DEMO_TARGETS]},
        "traps": [{"id": t.id, "trigger": t.trigger, "description": t.description, "folder": t.folder,
                   "files": _trap_files(t.folder)} for t in TRAPS],
    }


def render() -> str:
    return json.dumps(build(), indent=1, ensure_ascii=False) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run python packaging/export_rules.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
